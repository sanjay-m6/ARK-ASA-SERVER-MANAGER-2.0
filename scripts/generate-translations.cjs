function setNested(obj, path, value) {
    const keys = path.split('.');
    let current = obj;
    for (let i = 0; i < keys.length - 1; i++) {
        if (!current[keys[i]]) current[keys[i]] = {};
        current = current[keys[i]];
    }
    current[keys[keys.length - 1]] = value;
}

function deepClone(obj) {
    return JSON.parse(JSON.stringify(obj));
}

for (const [lang, trans] of Object.entries(translations)) {
    const result = deepClone(en); // Start with English as fallback
    for (const [path, value] of Object.entries(trans)) {
        setNested(result, path, value);
    }
    const outPath = path.join(localesDir, `${lang}.json`);
    fs.writeFileSync(outPath, JSON.stringify(result, null, 2), 'utf8');
    console.log(`✅ Generated ${lang}.json`);
}

